#### build-report.R  -  results/*.csv -> results/tables.md (+ results/versions.md) ####
#   Rscript build-report.R

suppressPackageStartupMessages(library(dplyr))
source("R/backends.R"); source("R/tasks.R")
md_table <- function(df) {
  df <- mutate(df, across(everything(), \(x) ifelse(is.na(x), "", as.character(x))))
  c(paste0("| ", paste(names(df), collapse = " | "), " |"),
    paste0("|", paste(rep("---", ncol(df)), collapse = "|"), "|"),
    apply(df, 1, \(r) paste0("| ", paste(gsub("\\|", "\\\\|", r), collapse = " | "), " |")))
}
fmt_s <- \(s) ifelse(s < 0.1, sprintf("%.3f", s), ifelse(s < 10, sprintf("%.2f", s), sprintf("%.0f", s)))
out <- c("# dplyr backends: result tables", "",
         "Generated by `build-report.R` from `results/*.csv`. Explanations: [README.md](../README.md).", "")

## benchmark tables, one per data size ----
bench_files <- sort(Sys.glob("results/bench_n*.csv"))
if (nzchar(Sys.getenv("REPORT_SIZES")))      # e.g. REPORT_SIZES=100000,1000000 while a bigger run is still going
  bench_files <- bench_files[sub("results/bench_n(.*)\\.csv", "\\1", bench_files) %in% strsplit(Sys.getenv("REPORT_SIZES"), ",")[[1]]]
for (f in bench_files) {
  r <- readr::read_csv(f, show_col_types = FALSE, col_types = readr::cols(.default = "c")) |>
    mutate(across(c(secs, convert_s, peak_mb, base_mb, n), as.numeric), threads = as.integer(threads),
           # fallback flag from the captured messages (duckplyr says "falling back", arrow "pulling data into R")
           status = if_else(status == "ok" & grepl("fallback|falling back|pulling data into R", note, ignore.case = TRUE), "ok (fallback)", status))
  n <- r$n[1]
  r_all <- r
  r <- r |> filter(threads == max(threads))     # main table: all cores; fewer-thread reruns go to the threads table
  ref <- r |> filter(backend == "dplyr") |> select(task, ref = secs)
  cell <- r |>
    left_join(ref, by = "task") |>
    mutate(cell = case_when(
      status == "ok"            ~ sprintf("%s (%s×)", fmt_s(secs), sprintf("%.1f", ref / secs)),
      status == "ok (fallback)" ~ sprintf("%s (%s×) fb", fmt_s(secs), sprintf("%.1f", ref / secs)),
      status == "WRONG"         ~ sprintf("**WRONG** %s", fmt_s(secs)),
      .default = status))
  bk_order <- intersect(BACKENDS, unique(r$backend))
  wide <- cell |>
    select(backend, task, cell) |>
    tidyr::pivot_wider(names_from = task, values_from = cell) |>
    mutate(backend = factor(backend, bk_order)) |> arrange(backend) |> mutate(backend = as.character(backend))
  wide <- wide[c("backend", intersect(names(TASKS), names(wide)))]
  # total over the 9 single-step tasks (pipeline separate), only where every task ran ok
  # dplyr+collapse only rewrites the grouped steps: its other steps ARE dplyr, so count dplyr's time for them
  hyb <- cell |> filter(backend == "dplyr+collapse", status == "n/a") |> select(backend, task) |>
    left_join(cell |> filter(backend == "dplyr") |> select(task, secs, status), by = "task")
  tot <- cell |> filter(!(backend == "dplyr+collapse" & status == "n/a")) |> bind_rows(hyb) |> filter(task != "pipeline") |> summarise(
    total = if (all(status %in% c("ok", "ok (fallback)")) && n() == length(TASKS) - 1) sum(secs) else NA_real_,
    peak_mb = suppressWarnings(max(peak_mb, na.rm = TRUE)), .by = backend)
  wide <- wide |> left_join(tot, by = "backend") |>
    mutate(total = ifelse(is.na(total), "-", sprintf("%s (%.1f×)", fmt_s(total), total[backend == "dplyr"] / total)),
           peak_mb = ifelse(is.finite(peak_mb), round(peak_mb), NA))
  out <- c(out, sprintf("## n = %s units (%s threads)", format(n, big.mark = ",", scientific = FALSE), r$threads[1]), "",
           "Seconds per task (best of up to 3 runs, collect to tibble included, conversion excluded) and speed-up vs dplyr.",
           "`fb` = ran, but (partly) fell back to dplyr/R. **WRONG** = ran, result differs from dplyr. `n/a` = not applicable.",
           "`total` = sum of the 9 single-step tasks, only if all ran (dplyr+collapse: dplyr's time for the steps it leaves as dplyr). `peak_mb` = highest peak RSS of the process (data included; multidplyr's workers not counted).", "",
           md_table(wide), "")
  conv <- r |> filter(!is.na(convert_s)) |> summarise(convert_s = max(convert_s), .by = backend)
  out <- c(out, "Conversion from tibble to the backend's object, slowest task's input (s): ",
           paste(sprintf("%s %s", conv$backend, fmt_s(conv$convert_s)), collapse = " · "), "")
  if (length(unique(r_all$threads)) > 1) {
    th <- r_all |> filter(status %in% c("ok", "ok (fallback)")) |>
      select(backend, task, threads, secs) |>
      tidyr::pivot_wider(names_from = threads, values_from = secs, names_prefix = "t") |>
      filter(!is.na(.data[[paste0("t", min(r_all$threads))]]))
    lo <- paste0("t", min(r_all$threads)); hi <- paste0("t", max(r_all$threads))
    th <- th |> transmute(backend, task, !!sprintf("%s thread(s), s", min(r_all$threads)) := fmt_s(.data[[lo]]),
                          !!sprintf("%s threads, s", max(r_all$threads)) := fmt_s(.data[[hi]]),
                          speedup = sprintf("%.1f×", .data[[lo]] / .data[[hi]])) |> arrange(task, backend)
    out <- c(out, sprintf("### Threads at n = %s: %d vs %d", format(n, big.mark = ",", scientific = FALSE), min(r_all$threads), max(r_all$threads)), "",
             "dplyr is single-threaded, so its time is the same at any thread count.", "", md_table(th), "")
  }
  bad <- r |> filter(!status %in% c("ok", "n/a", "skipped")) |> select(task, backend, status, note) |>
    mutate(note = substr(gsub("\\s+", " ", note), 1, 220))
  if (nrow(bad)) out <- c(out, "<details><summary>Errors, fallbacks, wrong results (notes)</summary>", "", md_table(bad), "", "</details>", "")
}

## semantics ----
if (file.exists("results/01-semantics.csv")) {
  s <- readr::read_csv("results/01-semantics.csv", show_col_types = FALSE)
  sym <- s |> mutate(cell = case_when(
    outcome == "n/a" ~ "",
    outcome == "error" & backend == "dplyr" ~ "error",
    vals == "ERROR" & same_values ~ "error (same)",
    vals == "ERROR" ~ "error",
    same_values & same_types ~ "✓",
    same_values ~ paste0("✓ type: ", types),
    .default = paste0("**", substr(vals, 1, 40), "**")))
  ref <- s |> filter(backend == "dplyr") |> transmute(case, what, dplyr = substr(vals, 1, 40))
  wide <- sym |> filter(backend != "dplyr") |> select(case, backend, cell) |>
    tidyr::pivot_wider(names_from = backend, values_from = cell)
  wide <- ref |> left_join(wide, by = "case")
  out <- c(out, "## 01 semantics: same dplyr code, same answer?", "",
           "`✓` = same values and types as dplyr. `✓ type:` = same values, other type. **bold** = different values (shown). Values are the key column(s), rows sorted unless order is the point.", "",
           md_table(wide), "")
}

