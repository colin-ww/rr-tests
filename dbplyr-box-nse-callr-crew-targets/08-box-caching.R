# Part 8 (issue #5): does targets re-run the right targets when functions come from box::use() instead of tar_source()?
# Writes one mini targets project per variant into targets/cache_<variant>/. Every variant has the same two functions
# (add_x, add_y) in R/clean.R and the targets raw -> out_x, out_y. Runs each with a fresh store (no controller, crew).
# Then, with no controller, makes one change at a time (to R/clean.R or the project folder), asks a fresh tar_outdated()
# which targets it would re-run, and undoes the change (text and modification time).
suppressPackageStartupMessages(library(dplyr))
source("R/harness.R")                 # squish(), clip(), save_results()
root <- file.path(getwd(), "targets")
T0 <- as.POSIXct("2026-01-01 00:00:00", tz = "UTC")   # fixed modification time, so undoing a change is exact

# ---- the code file each variant uses (R/clean.R) ------------------------------------------------
CLEAN <- c("box::use(dplyr[mutate])", "",
  "#' @export", "add_x <- function(d) mutate(d, x = var1 * 2)", "",
  "#' @export", "add_y <- function(d) mutate(d, y = var1 * 2)")
helper_file <- \(helper) c(helper, "",
  "add_x <- function(d) {", "  clean_imports()", "  mutate(d, x = var1 * 2)", "}", "",
  "add_y <- function(d) {", "  clean_imports()", "  mutate(d, y = var1 * 2)", "}")
HELPER_NAIVE <- helper_file(c("# the issue's idea, as written", "clean_imports <- function() {", "  box::use(dplyr[mutate])", "}"))
HELPER_FIXED <- helper_file(c("# runs box::use() in the function that calls clean_imports(), so the imports land there",
  "clean_imports <- function() eval.parent(quote(box::use(dplyr[mutate])))"))
LIST <- c("# no box at all: a plain list of functions", "clean <- list(",
  "  add_x = function(d) dplyr::mutate(d, x = var1 * 2),", "  add_y = function(d) dplyr::mutate(d, y = var1 * 2)", ")")

ENVIR <- r"(tar_option_set(envir = new.env(parent = globalenv())))"
SCOPED <- c(ENVIR,
  "# like tar_source(), but each file gets its own scope: its box::use() imports are seen by that file only",
  r"(source_scoped <- function(dir = "R", envir = tar_option_get("envir")) {)",
  r"(  for (f in list.files(dir, "\\.[rR]$", full.names = TRUE, recursive = TRUE)) {)",
  "    file_env <- new.env(parent = envir)",
  "    sys.source(f, envir = file_env, keep.source = FALSE)",
  "    list2env(as.list(file_env), envir)",
  "  }", "}", "source_scoped()")
tg <- \(prefix = "") c("list(", "  tar_target(raw, data.frame(var1 = 1:3)),",
  sprintf("  tar_target(out_x, %sadd_x(raw)),", prefix), sprintf("  tar_target(out_y, %sadd_y(raw))", prefix), ")")
v <- \(variant, about, setup, file = CLEAN, tgts = tg()) tibble(variant, about, setup = list(setup), file = list(file), tgts = list(tgts))

variants <- bind_rows(
  v("src_global",       "tar_source() (functions in the global env; box::use() at the top of R/clean.R)", "tar_source()"),
  v("src_envir",        "tar_option_set(envir = new.env()) + tar_source()", c(ENVIR, "tar_source()")),
  v("src_scoped",       "tar_option_set(envir = new.env()) + source_scoped(): tar_source() with one scope per file", SCOPED),
  v("src_helper_naive", "tar_source(); each function calls clean_imports() = function() box::use(...)", "tar_source()", HELPER_NAIVE),
  v("src_helper_fixed", "tar_source(); each function calls clean_imports() = function() eval.parent(quote(box::use(...)))",
    "tar_source()", HELPER_FIXED),
  v("src_list",         "tar_source() of a plain list of functions (no box), clean$add_x(raw)", "tar_source()", LIST, tg("clean$")),
  v("mod_object",       "options(box.path = getwd()) + box::use(R/clean), clean$add_x(raw)",
    c("options(box.path = getwd())", "box::use(R/clean)"), tgts = tg("clean$")),
  v("mod_attach",       "options(box.path = getwd()) + box::use(R/clean[add_x, add_y]), add_x(raw)",
    c("options(box.path = getwd())", "box::use(R/clean[add_x, add_y])")),
  v("mod_in_fn",        "options(box.path = getwd()) + box::use(R/clean) inside wrapper functions in _targets.R",
    c("options(box.path = getwd())",
      "add_x <- function(d) {\n  box::use(R/clean)\n  clean$add_x(d)\n}", "add_y <- function(d) {\n  box::use(R/clean)\n  clean$add_y(d)\n}"))
)

# ---- write the projects ------------------------------------------------------------------------
header <- \(about) c(paste("#", about),
  "# Generated by ../../08-box-caching.R. Run here: Rscript -e 'targets::tar_make()'  (USE_CREW=true for crew)",
  "library(targets)",
  r"(if (Sys.getenv("USE_CREW") == "true"))",
  r"(  tar_option_set(controller = crew::crew_controller_local(name = "crew", workers = 2, seconds_idle = 10)))",
  r"(tar_option_set(error = "continue")   # every target reports its own outcome)", "")
code_file <- \(dir) file.path(dir, "R", "clean.R")
write_project <- \(variant, about, setup, file, tgts) {
  dir <- file.path(root, paste0("cache_", variant)); unlink(dir, recursive = TRUE)
  dir.create(file.path(dir, "R"), recursive = TRUE)
  writeLines(c(header(about), setup, "", tgts), file.path(dir, "_targets.R"))
  writeLines(file, code_file(dir)); Sys.setFileTime(code_file(dir), T0)
  dir
}
dirs <- purrr::pmap_chr(variants, write_project)

# ---- run ---------------------------------------------------------------------------------------
# as 04-targets.R: fresh Rscript per call; TESTTHAT=true or R_BOX_PATH would change where box looks for modules
rscript <- \(dir, code, crew = FALSE) processx::run(file.path(R.home("bin"), "Rscript"), c("-e", code), wd = dir,
  error_on_status = FALSE, env = c("current", USE_CREW = tolower(crew), TESTTHAT = "false", R_BOX_PATH = ""))
store <- \(dir) file.path(dir, "_targets")
outdated <- \(dir) {
  r <- rscript(dir, "cat(targets::tar_outdated(reporter = 'silent'), sep = '\\n')")
  if (r$status != 0) return(paste("ERROR:", clip(squish(r$stderr), 150)))
  od <- intersect(c("out_x", "out_y"), strsplit(r$stdout, "\n")[[1]])
  if (length(od)) toString(od) else "none"
}
clean_err <- \(x) x |> sub(pattern = "(?s)^.*Error in tar_\\w+\\(\\):", replacement = "", perl = TRUE) |>
  sub(pattern = "(?s)See https.*$", replacement = "", perl = TRUE) |> squish() |> clip(200)

# each change returns the folder to check (or NA if it does not apply to this variant's file)
edit_text <- \(from, to) \(dir) {
  f <- code_file(dir); old <- readLines(f); new <- sub(from, to, old, fixed = TRUE)
  if (identical(old, new)) return(NA_character_)
  writeLines(new, f); dir
}
changes <- tribble(
  ~change, ~should_rerun, ~apply,
  "nothing (2nd run, new R session)",                   "none",            \(dir) dir,
  "file touched: same text, newer modification time",   "none",            \(dir) { Sys.setFileTime(code_file(dir), T0 + 86400); dir },
  "comment line added at the end of the file",          "none",            \(dir) { write("# checked by Colin", code_file(dir), append = TRUE); dir },
  "spaces only, in add_y (var1 * 2 -> var1*2)",         "none",            edit_text("y = var1 * 2", "y = var1*2"),
  "add_y changed (var1 * 2 -> var1 * 3)",               "out_y",           edit_text("y = var1 * 2", "y = var1 * 3"),
  "import list changed (dplyr[mutate] -> [mutate, filter])", "none or both", edit_text("dplyr[mutate]", "dplyr[mutate, filter]"),
  "project folder copied elsewhere (same file times)",  "none",            \(dir) { to <- paste0(dir, "_copy"); unlink(to, recursive = TRUE)
                                                                              dir.create(to); file.copy(list.files(dir, all.files = TRUE, full.names = TRUE, no.. = TRUE),
                                                                                to, recursive = TRUE, copy.date = TRUE); to },
  "all changes undone",                                 "none",            \(dir) dir
)
undo <- \(dir, original) { writeLines(original, code_file(dir)); Sys.setFileTime(code_file(dir), T0); unlink(paste0(dir, "_copy"), recursive = TRUE) }

run_variant <- function(variant, about, ...) {
  dir <- file.path(root, paste0("cache_", variant)); original <- readLines(code_file(dir))
  runs <- purrr::map(c(none = FALSE, crew = TRUE), \(crew) {
    unlink(store(dir), recursive = TRUE)
    r <- rscript(dir, "targets::tar_make(reporter = 'silent')", crew)
    m <- tryCatch(targets::tar_meta(fields = error, store = store(dir)), error = \(e) tibble(name = character(), error = character()))
    e <- purrr::map_chr(c("out_x", "out_y"), \(t) { x <- m$error[m$name == t]
      if (!length(x)) paste("never ran:", clean_err(r$stderr)) else if (is.na(x)) NA_character_ else clean_err(x) })
    if (is.na(e[1]) && is.na(e[2])) "works" else paste("FAILS:", coalesce(e[1], e[2]))
  })
  res <- tibble(part = "run", variant, about, change = c("tar_make(), no controller", "tar_make(), crew"),
                should_rerun = NA_character_, result = unlist(runs))
  if (runs[["none"]] == "works") {                     # the store now holds the crew run: rebuild without a controller
    unlink(store(dir), recursive = TRUE); rscript(dir, "targets::tar_make(reporter = 'silent')")
    res <- bind_rows(res, purrr::pmap(changes, \(change, should_rerun, apply) {
      check <- apply(dir); on.exit(undo(dir, original))
      tibble(part = "change", variant, about, change, should_rerun, result = if (is.na(check)) "n/a" else outdated(check))
    }) |> purrr::list_rbind())
  }
  unlink(store(dir), recursive = TRUE)
  res
}

t0 <- Sys.time()
res <- purrr::pmap(variants, run_variant, .progress = "variants") |> purrr::list_rbind()

# ---- why: what targets hashes for a box module vs a function (fresh R process) -----------------------
why <- callr::r(\(dir, T0) {
  setwd(dir); options(box.path = getwd()); f <- "R/clean.R"
  hashes <- \() callr::r(\(dir) { setwd(dir); options(box.path = getwd()); box::use(R/clean)
    c(module = secretbase::siphash13(clean),                                   # what targets does for a box module
      fn = secretbase::siphash13(targets::tar_deparse_safe(clean$add_x)))      # what targets does for a function
  }, args = list(getwd()), env = c(callr::rcmd_safe_env(), TESTTHAT = "false", R_BOX_PATH = ""))
  h0 <- hashes(); Sys.setFileTime(f, T0 + 86400); h1 <- hashes(); Sys.setFileTime(f, T0)
  box::use(R/clean)
  m0 <- secretbase::siphash13(clean); invisible(clean$add_x(data.frame(var1 = 1))); m1 <- secretbase::siphash13(clean)
  sf <- attr(attr(clean$add_x, "srcref"), "srcfile")
  list(class = toString(class(clean)), srcfile = toString(sort(ls(sf))),
       filename_absolute = startsWith(sf$filename, "/"), wd = identical(sf$wd, getwd()),
       timestamp_is_mtime = identical(as.numeric(sf$timestamp), as.numeric(file.mtime(f))),
       lines_are_whole_file = identical(sf$lines, readLines(f)),
       touch_changes_module_hash = h0[["module"]] != h1[["module"]], touch_changes_fn_hash = h0[["fn"]] != h1[["fn"]],
       first_call_changes_module_hash = m0 != m1)
}, args = list(file.path(root, "cache_mod_object"), T0), env = c(callr::rcmd_safe_env(), TESTTHAT = "false", R_BOX_PATH = ""))
res <- bind_rows(res, tibble(part = "why", variant = "mod_object", change = names(why), result = as.character(unlist(why))))

# ---- same R session: tar_make(callr_function = NULL), then tar_outdated(callr_function = NULL) ------
# two effects: box keeps loaded modules for the whole session, and R byte-compiles a function the first time it runs,
# which changes how the module object serializes (targets hashes the module that way)
in_session <- \(variant, edit, pre = "", mid = "") rscript(file.path(root, paste0("cache_", variant)), sprintf(r"(
  %s
  targets::tar_make(callr_function = NULL, reporter = "silent")
  f <- "R/clean.R"; old <- readLines(f)
  if (%s) writeLines(sub("y = var1 * 2", "y = var1 * 3", old, fixed = TRUE), f)
  %s
  od <- targets::tar_outdated(callr_function = NULL, reporter = "silent")
  fn <- if (exists("clean")) clean$add_y else add_y
  writeLines(old, f); Sys.setFileTime(f, as.POSIXct("2026-01-01", tz = "UTC")); unlink("_targets", recursive = TRUE)
  cat("outdated:", if (length(od)) toString(sort(od)) else "none", "| new add_y in use:", any(grepl("var1 * 3", deparse(fn), fixed = TRUE))))",
  pre, edit, mid))$stdout
res <- bind_rows(res, tribble(
  ~variant,     ~change,                                                    ~should_rerun, ~edit, ~pre,                      ~mid,
  "mod_object", "nothing edited",                                            "none",        FALSE, "",                        "",
  "mod_object", "nothing edited, byte-compiler off (compiler::enableJIT(0))", "none",       FALSE, "invisible(compiler::enableJIT(0))", "",
  "mod_object", "add_y edited",                                              "out_y",       TRUE,  "",                        "",
  "mod_object", "add_y edited, box::purge_cache() before tar_outdated()",    "out_y",       TRUE,  "",                        "box::purge_cache()",
  "src_global", "nothing edited",                                            "none",        FALSE, "",                        "",
  "src_global", "add_y edited",                                              "out_y",       TRUE,  "",                        ""
) |> mutate(part = "same_session", result = purrr::pmap_chr(list(variant, edit, pre, mid), in_session)) |> select(-edit, -pre, -mid))

# ---- custom envir: a constant defined in _targets.R itself vs in an R/ file ---------------------------------
read_val <- \(dir, name) tryCatch(paste(targets::tar_read_raw(name, store = store(dir)), collapse = ","), error = \(e) NA_character_)
first_error <- \(dir, r, name) {
  force(r)   # run tar_make() before reading its metadata
  e <- tryCatch(targets::tar_meta(fields = error, store = store(dir)) |> filter(name == !!name) |> pull(error), error = \(e) character())
  if (length(e) && is.na(e)) "works" else paste("FAILS:", clean_err(if (length(e)) e else r$stderr))
}
const_check <- function(tag, in_targets_r) {
  dir <- file.path(root, paste0("cache_envir_const_", tag)); unlink(dir, recursive = TRUE)
  dir.create(file.path(dir, "R"), recursive = TRUE); writeLines(CLEAN, code_file(dir))
  const_file <- file.path(dir, if (in_targets_r) "_targets.R" else "R/settings.R")
  if (!in_targets_r) writeLines("multiplier <- 10", const_file)
  writeLines(c(header(paste("src_envir + a constant defined in", if (in_targets_r) "_targets.R itself" else "R/settings.R")),
    ENVIR, "tar_source()", if (in_targets_r) "multiplier <- 10", "",
    "list(", "  tar_target(raw, data.frame(var1 = 1:3)),", "  tar_target(out_m, raw$var1 * multiplier)", ")"), file.path(dir, "_targets.R"))
  runs <- purrr::map_chr(c(FALSE, TRUE), \(crew) {
    unlink(store(dir), recursive = TRUE); first_error(dir, rscript(dir, "targets::tar_make(reporter = 'silent')", crew), "out_m") })
  unlink(store(dir), recursive = TRUE); rscript(dir, "targets::tar_make(reporter = 'silent')")
  old <- readLines(const_file); writeLines(sub("multiplier <- 10", "multiplier <- 20", old, fixed = TRUE), const_file)
  od <- rscript(dir, "cat(targets::tar_outdated(reporter = 'silent'))")$stdout
  writeLines(old, const_file); unlink(store(dir), recursive = TRUE)
  tibble(part = "envir_const", variant = paste0("envir_const_", tag), should_rerun = c(NA, NA, "out_m"),
    change = c("tar_make(), no controller", "tar_make(), crew", "multiplier changed to 20: tar_outdated()"),
    result = c(runs, if (grepl("out_m", od)) "out_m" else "none"))
}
lg <- rscript(file.path(root, "cache_src_envir"), r"(targets::tar_load_globals(); a <- exists("add_x")
  b <- exists("add_x", targets::tar_option_get("envir"), inherits = FALSE)
  attach(targets::tar_option_get("envir"), name = "pipeline"); cat(a, b, exists("add_x")))")$stdout
res <- bind_rows(res, const_check("top", TRUE), const_check("rfile", FALSE), tibble(part = "envir_const", variant = "src_envir",
  change = "tar_load_globals(): add_x in my session? / in tar_option_get('envir')? / in my session after attach()?", result = lg))

# ---- one scope per file? R/util.R imports n_distinct; R/clean.R uses it without importing it ---------------
UTIL <- c("box::use(dplyr[n_distinct])", "", "times2 <- function(v) v * 2", "count_ids <- function(v) n_distinct(v)")
CLEAN2 <- c("box::use(dplyr[mutate])", "",
  "add_x <- function(d) mutate(d, x = times2(var1))   # times2() is defined in R/util.R",
  "add_y <- function(d) mutate(d, y = var1 + 1)",
  "leaky <- function(d) n_distinct(d$var1)            # n_distinct is imported by R/util.R only")
scope_check <- function(variant, setup) {
  dir <- file.path(root, paste0("cache_2files_", variant)); unlink(dir, recursive = TRUE); dir.create(file.path(dir, "R"), recursive = TRUE)
  writeLines(c(header(paste(variant, "with two files: does R/clean.R see the imports of R/util.R?")), setup, "",
    "list(", "  tar_target(raw, data.frame(var1 = 1:3)),", "  tar_target(out_x, add_x(raw)),", "  tar_target(out_y, add_y(raw)),",
    "  tar_target(own_import, count_ids(raw$var1)),",
    r"(  tar_target(other_files_import, tryCatch(leaky(raw), error = \(e) paste("error:", conditionMessage(e)))))", ")"),
    file.path(dir, "_targets.R"))
  writeLines(UTIL, file.path(dir, "R", "util.R")); writeLines(CLEAN2, code_file(dir))
  runs <- purrr::map_chr(c(FALSE, TRUE), \(crew) {
    unlink(store(dir), recursive = TRUE); rscript(dir, "targets::tar_make(reporter = 'silent')", crew)
    sprintf("own file's import: %s | other file's import: %s", read_val(dir, "own_import"), read_val(dir, "other_files_import")) })
  util <- file.path(dir, "R", "util.R"); old <- readLines(util); writeLines(sub("v * 2", "v * 3", old, fixed = TRUE), util)
  od <- outdated(dir); writeLines(old, util); unlink(store(dir), recursive = TRUE)
  tibble(part = "two_files", variant, should_rerun = c(NA, NA, "out_x"),
         change = c("tar_make(), no controller", "tar_make(), crew", "times2() in R/util.R changed: tar_outdated()"), result = c(runs, od))
}
res <- bind_rows(res, scope_check("src_envir", c(ENVIR, "tar_source()")), scope_check("src_scoped", SCOPED))

save_results(res, "08-box-caching.csv")
cat("rows:", nrow(res), " runtime:", format(round(Sys.time() - t0)), "\n")
res |> select(part, variant, change, should_rerun, result) |> print(n = Inf, width = 250)
