# Builds results/tables.md (summary tables per part), results/*.png (charts) and results/versions.md
suppressPackageStartupMessages({library(dplyr); library(tidyr); library(readr); library(ggplot2)})
rd <- \(f) if (file.exists(file.path("results", f))) read_csv(file.path("results", f), show_col_types = FALSE) else NULL
md_table <- \(df) {
  df <- mutate(df, across(everything(), \(x) ifelse(is.na(x), "", gsub("\\|", "\\\\|", as.character(x)))))
  c(paste0("| ", paste(names(df), collapse = " | "), " |"), paste0("|", strrep("---|", ncol(df))),
    apply(df, 1, \(r) paste0("| ", paste(r, collapse = " | "), " |")), "")
}
s <- \(x) ifelse(is.na(x), NA, ifelse(x < 0.1, sprintf("%.3f", x), ifelse(x < 10, sprintf("%.2f", x), sprintf("%.0f", x))))
eng_lab <- c(mssql = "SQL Server (odbc)", oracle = "Oracle (odbc)", roracle = "Oracle (ROracle)", duckdb = "duckdb (in-process)")
eng_col <- c(mssql = "#2a78d6", oracle = "#eb6834", roracle = "#1baf7a", duckdb = "#eda100")   # dataviz palette slots 1-4
theme_bm <- theme_minimal(base_size = 11) +
  theme(panel.grid.minor = element_blank(), panel.grid.major = element_line(colour = "#e7e6e2", linewidth = 0.3),
        legend.position = "top", plot.background = element_rect(fill = "#fcfcfb", colour = NA),
        strip.text = element_text(face = "bold", hjust = 0), axis.text = element_text(colour = "#52514e"),
        plot.title.position = "plot", plot.caption = element_text(colour = "#52514e", hjust = 0))
out <- c("# Result tables (auto-generated by build-report.R)", "",
         "Times are seconds: median of the repeated calls in a fresh R process (`med_s`), see R/bench.R. Engines: ",
         paste0("`", names(eng_lab), "` = ", eng_lab, collapse = ", "), ".", "")

# --- 01 method ---
m <- rd("01-method.csv")
if (!is.null(m)) {
  out <- c(out, "## 01 Measuring method", "", "### a. One R process, calls in a row (`collect()` of a 1e6-row table)", "",
           m |> filter(startsWith(part, "a.")) |> transmute(engine, table = small, phase, med_s = s(med_s)) |>
             pivot_wider(names_from = engine, values_from = med_s) |> md_table(),
           "### b. `bench::mark(iterations = 5)` settings", "",
           m |> filter(startsWith(part, "b.")) |> transmute(engine, table, setting, total_wall_s = s(wall_s), median_s = s(median_s),
                                                            mem_alloc_mb = round(mem_alloc_mb), n_itr, n_gc, warning) |> md_table(),
           "### c/d. `interruptible`, `collect()` vs `dbGetQuery()` (fresh process each)", "",
           m |> filter(startsWith(part, "c")) |> transmute(engine, table = paste0(type, " ", rows), how, med_s = s(med_s)) |>
             pivot_wider(names_from = how, values_from = med_s) |> md_table())
}

# --- 02 mutate ---
mu <- rd("02-mutate.csv"); lz <- rd("02-lazy.csv")
if (!is.null(mu)) out <- c(out, "## 02 mutate before or after collect()", "",
  mu |> transmute(rows = format(rows, scientific = TRUE), case, engine, med_s = s(med_s)) |>
    pivot_wider(names_from = engine, values_from = med_s) |> md_table())
if (!is.null(lz)) out <- c(out, "### Building the lazy query (bench::mark, milliseconds)", "",
  lz |> filter(!is.na(median_ms)) |> transmute(engine, what, median_ms = sprintf("%.2f", median_ms)) |>
    pivot_wider(names_from = engine, values_from = median_ms) |> md_table(),
  "### `age + 1` vs `age + 1L`: SQL and the R class you get back", "",
  lz |> filter(!is.na(age_class)) |> transmute(engine, what, age_class, sql = paste0("`", sql, "`")) |> md_table())

# --- 03 collect grid ---
co <- rd("03-collect.csv"); ty <- rd("03-r-types.csv")
if (!is.null(ty)) out <- c(out, "## 03 collect() by type, rows, columns", "", "### What each database type becomes in R", "",
  ty |> transmute(engine, type, db_type, r_class) |> md_table())
if (!is.null(co)) {
  nar <- co |> filter(k == 1)
  out <- c(out, "### Seconds per collect(), 1 column", "",
           nar |> transmute(type, rows = format(rows, scientific = TRUE), engine, v = if ("error" %in% names(nar)) ifelse(is.na(med_s), "error", s(med_s)) else s(med_s)) |>
             pivot_wider(names_from = c(engine), values_from = v) |> arrange(type, rows) |> md_table(),
           "### Nanoseconds per value (cell), wide tables", "",
           co |> filter(type %in% c("int_rand", "dbl", "chr20_lo"), rows %in% c(1e5, 1e6)) |>
             transmute(type, rows = format(rows, scientific = TRUE), k, engine, ns = round(ns_per_cell)) |>
             pivot_wider(names_from = engine, values_from = ns) |> arrange(type, rows, k) |> md_table(),
           "### Memory: R object size vs extra peak RSS during the first collect (MB), 1e7 rows", "",
           nar |> filter(rows == 1e7) |> transmute(type, engine, mem = paste0(round(obj_mb), " / ", round(peak_mb))) |>
             pivot_wider(names_from = engine, values_from = mem) |> md_table())
  p <- nar |> filter(!is.na(med_s)) |>
    ggplot(aes(rows, med_s, colour = engine)) + geom_line(linewidth = 0.7) + geom_point(size = 1.6) +
    scale_x_log10(breaks = 10^(5:8), labels = c("100k", "1M", "10M", "100M")) +
    scale_y_log10(labels = \(x) paste0(x, " s")) + facet_wrap(~type, ncol = 5) +
    scale_colour_manual(values = eng_col, labels = eng_lab, name = NULL) +
    labs(title = "collect() time by column type: 1 column, 100k to 100M rows", x = "rows (log scale)", y = "median seconds (log scale)",
         caption = "Sandbox: database on the same machine (no network). Absolute times will differ on your servers; compare the shapes.") + theme_bm
  ggsave("results/03-collect-by-type.png", p, width = 11, height = 6.5, dpi = 150, bg = "#fcfcfb")
}

# --- 04 convert / join ---
cj <- rd("04-convert-join.csv")
if (!is.null(cj)) out <- c(out, "## 04 Type conversion and joins: SQL or R?", "",
  cj |> transmute(rows = format(rows, scientific = TRUE), case, engine, med_s = if ("error" %in% names(cj)) ifelse(is.na(med_s), "error", s(med_s)) else s(med_s)) |>
    pivot_wider(names_from = engine, values_from = med_s) |> md_table())

# --- 05 IO ---
io <- rd("05-io.csv")
if (!is.null(io)) {
  w <- io |> select(dataset, format, step, med_s, size_mb, types_changed) |>
    pivot_wider(names_from = step, values_from = med_s)
  out <- c(out, "## 05 Write / read file formats", "",
           w |> transmute(dataset, format, write_s = s(write), read_warm_s = s(`read (warm cache)`), read_cold_s = s(`read (cold cache)`),
                          size_mb = round(size_mb, 1), types_changed) |> md_table())
  p <- io |> filter(dataset == "mix_1e7") |> mutate(step = factor(step, c("write", "read (warm cache)", "read (cold cache)"))) |>
    ggplot(aes(med_s, reorder(format, -med_s))) + geom_col(width = 0.6, fill = "#2a78d6") +
    facet_wrap(~step, nrow = 1) + labs(title = "Write and read times, 10M rows x 10 columns (bm_mix_1e7)", x = "median seconds", y = NULL,
                                       caption = "Local disk in the sandbox. Run 05 on your own disks (home, /tmp, filers): that's where the differences show.") + theme_bm
  ggsave("results/05-io.png", p, width = 11, height = 5, dpi = 150, bg = "#fcfcfb")
}

# --- 06 temp tables, 07 knobs ---
tt <- rd("06-temp-tables.csv")
if (!is.null(tt)) out <- c(out, "## 06 Temp tables", "", tt |> filter(!is.na(step)) |> select(engine, step, result) |> md_table(),
                           tt |> filter(!is.na(kind)) |> transmute(engine, table, kind, med_s = s(med_s)) |> md_table())
kn <- rd("07-driver-knobs.csv")
if (!is.null(kn)) out <- c(out, "## 07 Driver settings, chunks, streaming, parallel", "",
  kn |> transmute(part, engine, setting, table, med_s = if ("error" %in% names(kn)) ifelse(is.na(med_s), "error", s(med_s)) else s(med_s),
                  peak_mb = round(peak_mb)) |>
    pivot_wider(names_from = table, values_from = c(med_s, peak_mb)) |> select(where(\(x) !all(is.na(x)))) |> md_table())
writeLines(out, "results/tables.md")

# --- versions ---
pk <- c("dplyr", "dbplyr", "DBI", "odbc", "ROracle", "duckdb", "bench", "callr", "withr", "lobstr", "arrow", "nanoparquet", "qs2", "data.table", "readr", "vroom")
ver <- tibble(package = pk, version = purrr::map_chr(pk, \(p) tryCatch(as.character(packageVersion(p)), error = \(e) "-")))
writeLines(c(paste0("- R ", R.version$major, ".", R.version$minor, " on ", R.version$platform), "",
             md_table(ver)), "results/versions.md")
message("wrote results/tables.md, results/versions.md, results/*.png")
